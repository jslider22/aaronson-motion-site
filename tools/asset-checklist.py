#!/usr/bin/env python3
"""
Asset checklist — lists every image slot and video slot on the site and
whether it's filled yet. Writes ASSETS.md and prints a short summary.

Run from the project folder:
    python3 tools/asset-checklist.py
"""
import re
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


class Collector(HTMLParser):
    def __init__(self):
        super().__init__()
        self.images, self.embeds, self.links = [], [], []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "img" and a.get("src", "").startswith("assets/"):
            self.images.append((a["src"], a.get("alt", "")))
        elif tag == "a" and a.get("href", "").startswith("assets/"):
            self.links.append(a["href"])
        elif tag == "div" and "embed" in (a.get("class") or "").split():
            self.embeds.append(a)


def main():
    pages = sorted(p for p in ROOT.glob("*.html") if not p.name.startswith("_"))
    lines = [
        "# Asset checklist",
        "",
        "Generated by `python3 tools/asset-checklist.py` — re-run it after adding files.",
        "",
        "- **Images:** save the file at the exact path shown (same name, same folder).",
        "- **Videos:** paste the Vimeo or YouTube ID into that slot's `data-id=\"\"` in the page file.",
        "  Vimeo `https://vimeo.com/123456789` → `123456789` · YouTube `https://youtu.be/AbC123xyz` → `AbC123xyz`.",
        "  Unlisted Vimeo links (`vimeo.com/123456789/abcdef1234`) also need `data-hash=\"abcdef1234\"`.",
        "",
    ]
    todo_img = todo_vid = done_img = done_vid = 0
    for page in pages:
        c = Collector()
        c.feed(page.read_text(encoding="utf-8"))
        if not (c.images or c.embeds or c.links):
            continue
        lines += [f"## {page.name}", ""]
        for src, alt in c.images:
            ok = (ROOT / src).exists()
            done_img += ok; todo_img += not ok
            lines.append(f"- [{'x' if ok else ' '}] `{src}`" + (f" — {alt}" if alt else ""))
        for href in dict.fromkeys(c.links):
            ok = (ROOT / href).exists()
            done_img += ok; todo_img += not ok
            lines.append(f"- [{'x' if ok else ' '}] `{href}` (download file)")
        for e in c.embeds:
            prov = e.get("data-provider", "?")
            val = (e.get("data-id") or e.get("data-url") or e.get("data-src") or "").strip()
            ok = bool(val)
            done_vid += ok; todo_vid += not ok
            label = e.get("data-slot", "")
            lines.append(f"- [{'x' if ok else ' '}] **{prov}** `{label}`" + (f" = {val}" if ok else ""))
        lines.append("")
    (ROOT / "ASSETS.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Images/files: {done_img} added, {todo_img} still needed")
    print(f"Video slots:  {done_vid} filled, {todo_vid} still need an ID/link")
    print("Full list written to ASSETS.md")


if __name__ == "__main__":
    main()
